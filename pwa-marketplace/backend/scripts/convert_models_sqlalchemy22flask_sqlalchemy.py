"""
Convert a SQLAlchemy 2.0 DeclarativeBase models file (generated by sqlacodegen)
into a Flask-SQLAlchemy `db.Model` based models.py file.

Usage: (from backend/scripts folder)
  python convert_models_sql2_to_flask.py \
    --in ../app/shared/models_sql2orm_plain_sqlalchemy2.py \
    --out ../app/shared/models_plain_sqlalchemy22flask_sqlalchemy.py

Both args are optional, defaults to above paths. Standard of Python
files is to use underscores "_" not hyphens "-", in order to be able
to import them directly without using importlib and other libs. 
This is a best-effort text transformation. Review the output and adjust
relationship/back_populates/uselist/foreign_keys or imports as needed.

The script: 
- replaces `class X(Base):` with `class X(db.Model):`
- replaces `mapped_column(TYPE, ...)` with `db.Column(db.TYPE, ...)` (best effort)
- replaces `Mapped[...]` annotated attributes with plain assignments
- changes `relationship(...)` -> `db.relationship(...)`
- keeps __table_args__ (ForeignKeyConstraint / Index) intact and imports text/Index if present

It is not guaranteed to handle every edge case; inspect the result
"""

